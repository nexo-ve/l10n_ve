PLACEHOLDER_PATTERNS = [
    (re.compile(r"%(\([a-zA-Z_][a-zA-Z0-9_]*\)[a-zA-ZdiouxXeEfFgGcrs])"), "FMT_PERCENT"),
    (re.compile(r"%[a-zA-ZdiouxXeEfFgGcrs]"), "FMT_PERCENT_SIMPLE"),
    (re.compile(r"\{[a-zA-Z_][a-zA-Z0-9_]*\}"), "FMT_BRACE"),
    (re.compile(r"\{\{[a-zA-Z_][a-zA-Z0-9_]*\}\}"), "FMT_DOUBLE_BRACE"),
    (re.compile(r"<[^>]+>"), "HTML_TAG"),
    (re.compile(r"\$\{[^}]+\}"), "JS_EXPR"),
]


def should_keep_as_is(text):
    text = text.strip()
    if not text:
        return True
    for pattern in KEEP_AS_IS_PATTERNS:
        if pattern.match(text):
            return True
    return False


def is_spanish(text):
    return bool(SPANISH_HINT.search(text)) and not bool(ENGLISH_HINT.search(text))


def is_english(text):
    return bool(ENGLISH_HINT.search(text)) and not is_spanish(text)


def protect_placeholders(text):
    protected = text
    tokens = {}
    counter = 0
    for pattern, prefix in PLACEHOLDER_PATTERNS:
        def replacer(match, prefix=prefix):
            nonlocal counter
            token = f"__{prefix}_{counter}__"
            counter += 1
            tokens[token] = match.group(0)
            return token
        protected = pattern.sub(replacer, protected)
    return protected, tokens


def restore_placeholders(text, tokens):
    for token, original in tokens.items():
        text = text.replace(token, original)
    return text


def apply_glossary(text):
    if " " not in text and text in GLOSSARY:
        return GLOSSARY[text]
    return text


def translate_text(text, translator):
    if should_keep_as_is(text):
        return text
    if text in GLOSSARY:
        return GLOSSARY[text]
    if is_spanish(text):
        return text
    if is_english(text) or not is_spanish(text):
        protected, tokens = protect_placeholders(text)
        try:
            translated = translator._translator.translate(protected)
            time.sleep(translator._delay)
        except Exception as exc:
            print(f"  [WARN] Error traduciendo: {text[:60]!r} -> {exc}")
            translated = text
        translated = restore_placeholders(translated, tokens)
        translator._cache[text] = translated
        return translated
    return text


class Translator:
    def __init__(self, delay=0.05):
        self._translator = GoogleTranslator(source="en", target="es")
        self._cache = {}
        self._delay = delay

    def translate(self, text):
        if text in self._cache:
            return self._cache[text]
        result = translate_text(text, self)
        self._cache[text] = result
        return result


def translate_entry(entry, translator):
    if entry.msgid_plural:
        results = []
        for i in range(len(entry.msgstr_plural)):
            part = entry.msgid if i == 0 else entry.msgid_plural
            results.append(translator.translate(part))
        return results
    return translator.translate(entry.msgid)


def complete_po_file(po_path, translator, dry_run=False):
    po = polib.pofile(str(po_path))
    module = po_path.parent.parent.name
    filled = 0

    for entry in po:
        if entry.obsolete or not entry.msgid:
            continue
        needs_translation = not entry.translated() or entry.fuzzy
        if not needs_translation:
            continue
        if entry.msgid_plural:
            translations = translate_entry(entry, translator)
            for i in range(len(entry.msgstr_plural)):
                entry.msgstr_plural[i] = translations[i] if i < len(translations) else translations[0]
        else:
            entry.msgstr = translate_entry(entry, translator)
        entry.flags = [flag for flag in entry.flags if flag != "fuzzy"]
        filled += 1

    if filled and not dry_run:
        revision_date = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M%z")
        if po.metadata is None:
            po.metadata = {}
        po.metadata["PO-Revision-Date"] = revision_date
        po.metadata["Language"] = "es_VE"
        po.save(str(po_path))

    return module, filled


def parse_args():
    parser = argparse.ArgumentParser(
        description="Completa traducciones pendientes en archivos es_VE.po.",
    )
    parser.add_argument(
        "-m",
        "--modules",
        nargs="*",
        help="Módulos específicos a completar.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Solo muestra cuántas traducciones se completarían.",
    )
    parser.add_argument(
        "--delay",
        type=float,
        default=0.05,
        help="Retardo entre llamadas al traductor (segundos).",
    )
    return parser.parse_args()


def main():
    args = parse_args()
    po_files = sorted(REPO_ROOT.glob("*/i18n/es_VE.po"))
    if args.modules:
        po_files = [p for p in po_files if p.parent.parent.name in args.modules]

    translator = Translator(delay=args.delay)
    total_filled = 0

    print(f"Repositorio: {REPO_ROOT}")
    print(f"Archivos: {len(po_files)}")
    print()

    for po_path in po_files:
        module, filled = complete_po_file(po_path, translator, dry_run=args.dry_run)
        if filled:
            action = "completaría" if args.dry_run else "completó"
            print(f"[OK] {module}: {action} {filled} traducciones")
            total_filled += filled
        else:
            print(f"[SKIP] {module}: sin traducciones pendientes")

    print()
    print(f"Total: {total_filled} traducciones {'a completar' if args.dry_run else 'completadas'}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
